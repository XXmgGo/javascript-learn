// ========== JavaScript 严格模式 (Strict Mode) 学习 ==========

// 使用 "use strict"; 必须放在脚本或函数的最顶部
// 整个脚本启用严格模式：在文件最顶部声明
// 单个函数启用严格模式：在函数体内第一行声明

"use strict";


// ----------------------------------------
// 1. 严格模式下，变量必须先声明
// ----------------------------------------

// 非严格模式：给未声明的变量赋值，会隐式创建全局变量（不报错）
// 严格模式：会抛出 ReferenceError

/*
  下面这行在严格模式下会报错，先注释掉：
  x = 10; // ReferenceError: x is not defined
*/

let y = 20; // 正确：先声明再赋值
console.log("y =", y);


// ----------------------------------------
// 2. 严格模式下，不能删除变量、函数、函数参数
// ----------------------------------------

/*
  下面的代码在严格模式下都会报错：
  delete y;           // SyntaxError
  function foo() {}
  delete foo;         // SyntaxError
*/

// 只能删除对象的属性（且属性可配置）
const obj = { a: 1, b: 2 };
delete obj.a;  // OK
console.log("删除 obj.a 后:", obj); // { b: 2 }


// ----------------------------------------
// 3. 严格模式下，函数参数不能重名
// ----------------------------------------

/*
  下面的代码在严格模式下会报语法错误：
  function sum(a, a, b) {  // SyntaxError
    return a + a + b;
  }
*/

function sum(a, b, c) { // OK：参数名不重复
  return a + b + c;
}
console.log("sum(1, 2, 3) =", sum(1, 2, 3)); // 6


// ----------------------------------------
// 4. 严格模式下，this 的行为变化
// ----------------------------------------

// 非严格模式：普通函数中 this 指向全局对象（window / global）
// 严格模式：普通函数中 this 为 undefined

function showThis() {
  console.log("this =", this);
}
showThis(); // 严格模式输出：this = undefined


// ----------------------------------------
// 5. 严格模式下，禁止使用八进制字面量（0开头）
// ----------------------------------------

/*
  下面的代码在严格模式下会报错：
  let num = 017; // SyntaxError（0 开头的八进制被禁止）
*/

// 可以使用 0o 前缀表示八进制（ES6 规范）
let octalNum = 0o17;
console.log("0o17 =", octalNum); // 15


// ----------------------------------------
// 6. 严格模式下，不允许使用 with 语句
// ----------------------------------------

/*
  下面的代码在严格模式下会报语法错误：
  with (obj) {
    console.log(a, b);
  }
*/


// ----------------------------------------
// 7. 严格模式下，给只读属性赋值会报错
// ----------------------------------------

const frozenObj = Object.freeze({ name: "Alice" });
/*
  下面这行在严格模式下会报错：
  frozenObj.name = "Bob"; // TypeError: Cannot assign to read only property
*/


// ----------------------------------------
// 8. 严格模式下，禁止给不可扩展的对象添加属性
// ----------------------------------------

const sealedObj = Object.seal({ age: 20 });
/*
  下面这行在严格模式下会报错：
  sealedObj.newProp = "test"; // TypeError: Cannot add property
*/


// ----------------------------------------
// 9. 严格模式下，arguments 与参数不再关联
// ----------------------------------------

function testArgs(a, b) {
  a = 100; // 修改 a
  console.log("a =", a, "arguments[0] =", arguments[0]);
  // 非严格模式：a 和 arguments[0] 同步变化，都为 100
  // 严格模式：arguments[0] 仍然是传入的原始值，不会跟着变
}
testArgs(1, 2);
// 严格模式输出：a = 100 arguments[0] = 1


// ----------------------------------------
// 10. 严格模式下，保留字不能作为变量名
// ----------------------------------------

/*
  下面的代码在严格模式下会报错：
  let implements = 123; // SyntaxError
  let interface = "abc"; // SyntaxError
  let public = true; // SyntaxError
*/


// ----------------------------------------
// 运行示例
// ----------------------------------------

console.log("\n=== 严格模式学习完成 ===");
console.log("提示：把被注释的报错代码取消注释，即可看到相应的错误信息");

